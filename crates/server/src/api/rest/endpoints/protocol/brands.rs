//! The marks of the identity providers a person already recognises.
//!
//! Inline and only inline: the sign-in page dials no third-party host, so
//! a brand's mark ships with the page or not at all. Monochrome marks draw
//! in `currentColor` and follow the theme; the two whose identity is their
//! colours keep them in both schemes, as the brands themselves do.

/// The inline mark for a recognised provider, matched on how operators
/// actually name them. Unknown providers get no mark here; the page shows
/// their initial instead, which promises nothing it cannot keep.
pub fn mark_of(named: &str) -> Option<&'static str> {
    let named = named.to_lowercase();
    if named.contains("google") {
        return Some(GOOGLE);
    }
    if named.contains("github") {
        return Some(GITHUB);
    }
    if named.contains("microsoft") || named.contains("entra") || named.contains("azure") {
        return Some(MICROSOFT);
    }
    if named.contains("apple") {
        return Some(APPLE);
    }
    if named.contains("okta") {
        return Some(OKTA);
    }
    None
}

